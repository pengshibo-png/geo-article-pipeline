def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()

    con = sqlite3.connect(ROOT / "data" / "app.db")
    row = con.execute("SELECT content FROM brand WHERE tenant_id='local'").fetchone()
    old = (row[0] if row else "") or ""
    if not old:
        print("品牌资料为空，终止")
        con.close()
        return 1

    left = [w for w in FORBIDDEN if w in NEW]
    print(f"原字数 {len(old)} → 新字数 {len(NEW)}")
    print("残留违禁/矛盾词:", left or "无 ✓")
    if left:
        con.close()
        return 2

