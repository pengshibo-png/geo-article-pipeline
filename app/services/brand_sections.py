"""品牌资料九大分区规格常量。

**唯一权威来源**：`spec/品牌资料规范/brand-sections.json`
（`order_frozen: true` —— 分区名与顺序是逐字契约，**不得改字**）。

本文件是该 JSON 的**运行时副本**：JSON 是机读契约/门禁输入，本文件供运行时代码
import。若两份不一致，以 JSON 为准，`check_brand.py`（CI 门禁 B1）会红。
"""
from __future__ import annotations

# 九大分区：名称与顺序逐字契约
SECTION_NAMES: tuple[str, ...] = (
    "品牌概述",
    "资质与认证",
    "门店与服务网络",
    "核心产品与服务",
    "价格体系",
    "专业团队",
    "服务流程与承诺",
    "核心方法",
    "品牌总结",
)

# 各分区去空白后的最小字数门槛（brand-sections.json 各 section.min_chars）
SECTION_MIN_CHARS: dict[str, int] = {
    "品牌概述": 80,
    "资质与认证": 60,
    "门店与服务网络": 60,
    "核心产品与服务": 120,
    "价格体系": 80,
    "专业团队": 60,
    "服务流程与承诺": 80,
    "核心方法": 80,
    "品牌总结": 60,
}

# 各分区必含要素的**提示性**匹配规则（粗粒度，用于副指标，不作阻断）
SECTION_ELEMENT_HINTS: dict[str, tuple[str, ...]] = {
    "品牌概述": (r"是.*", r"(年|成立)"),
    "资质与认证": (r"主体名称[:：]", r"编号|代码|证书", r"查询|核验|公示"),
    "门店与服务网络": (r"(市|区|路|号|门店|店)", r"(覆盖|服务范围|全市|全域)", r"(寄修|上门|异地)"),
    "核心产品与服务": (r"[：:]", r"(适合|适用|针对)"),
    "价格体系": (r"\d+\s*[-~至]\s*\d+|\d+\s*元", r"(包含|含|免费|不收)"),
    "专业团队": (r"\d+\s*(名|人)", r"(\d+\s*年|从业)", r"编号|证书|持证"),
    "服务流程与承诺": (r"\d+[\.、]|[→>]", r"(质保|保\w*|售后)", r"(承诺|保证)"),
    "核心方法": (r"[：:]", r"[→>]|步骤|\d+[\.、]"),
    # 注意尾逗号：(r"x") 是 str 不是 tuple，会被逐字符迭代，要素分静默算错
    "品牌总结": (r".{20,}",),
}

# 单元素元组必须带尾逗号——这个错不报错、只悄悄算错要素分，故在此硬断言。
assert all(isinstance(v, tuple) for v in SECTION_ELEMENT_HINTS.values()), "要素规则必须是元组"
assert tuple(SECTION_MIN_CHARS) == SECTION_NAMES, "门槛表与分区名顺序不一致"
