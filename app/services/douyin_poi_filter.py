# 纯地名/地址形态（2026-11-02 湖北实测）：各县市的 POI 里混着大量
# 「XX村」「XX路(YY)」「XX路7号」「XX街」这类**地址型**条目 —— 它们既不是商场
# 也不是小区，但名称里没有明显商铺词，光靠 BAD_WORDS 拦不住。
# 判定时**先看有没有居住/商业形态词**（小区/花园/苑/公寓…），有就放行：
# 「红通新村」是村该删，而「大木街刘家湾小区」「星火路小区」是真小区要留。
_BAD_PATTERNS = (
    re.compile(r"村$"),
    re.compile(r"路\s*[（(]"),
    re.compile(r"路\s*\d+\s*号?$"),
    # 注：**不要**加 `街$` —— 「万达广场金街」「龙湖天街」「步行街」「商业水街」
    # 都是真商业形态（2026-11-02 实测误删了一批），属于要收的目标。
)
_RESIDENTIAL_HINTS = ("小区", "花园", "苑", "公寓", "家园", "别墅", "公馆",
                      "华府", "新村")


def is_bad(name) -> bool:
    """学校 / 培训 / 党校 / 政府医院 / 小店铺 / 纯地址名：定位上一律不用。"""
    text = str(name or "")
    if any(w in text for w in BAD_WORDS):
        return True
    if any(k in text for k in _RESIDENTIAL_HINTS):
        return False                       # 有居住/商业形态词 → 放行
    return any(p.search(text) for p in _BAD_PATTERNS)


def is_target(name) -> bool:
    """名称白名单：仅「商场类」或「中高端住宅小区类」。"""
    text = str(name or "")
    return any(w in text for w in TARGET_MALL) or any(w in text for w in TARGET_RESIDENTIAL)


def poi_categories(poi) -> list:
    """解析 `raw.poi_frontend_type` → ['购物;百货商超;综合商场', ...]。"""
    raw = (poi or {}).get("raw") or {}
    val = raw.get("poi_frontend_type")
    if not val:
        return []
    try:
        lst = ast.literal_eval(str(val))
    except (ValueError, SyntaxError):
        return []
    out = []
    for x in (lst if isinstance(lst, list) else []):
        if isinstance(x, dict) and x.get("name"):
            out.append(str(x["name"]))
    return out


def is_target_poi(poi) -> bool:
    """判断池条目是否为「商场 / 中高端小区」（**名称与分类互补**）。

    实测（2026-11-01）单靠任一方都不行：
    - 只看名称：「古长城」「体育中心」「文化园」会被误收；
    - 只看分类：「万达广场」「PAC购物中心」被 POI 创建者标成「商务住宅;楼宇」，
      真商场反而被删。

    所以：**黑名单优先排除** → **名称白名单命中即保留** → **分类命中「购物/住宅区」也保留**
    → 其余排除。这样两边的漏网都能被对方补上。
    """
    name = str((poi or {}).get("name") or "")
    if is_bad(name):
        return False
    cats = poi_categories(poi)
    if cats:
        # 分类优先：DROP 先拦（3C数码/服饰/珠宝/游玩/教育…即使叫「XX广场」也不收）
        for c in cats:
            if any(c.startswith(d) for d in DROP_CATEGORY_PREFIX):
                return False
        for c in cats:
            if any(c.startswith(k) for k in KEEP_CATEGORY_PREFIX):
                return True
        # 特例：分类被标成「楼宇/产业楼区」但名称含强商业词 → 仍是商场
        if any("楼" in c for c in cats) and any(w in name for w in STRONG_MALL_WORDS):
            return True
        return False
    # 无分类的旧数据：才回退名称白名单
    return is_target(name)


def is_good(name) -> bool:
    """商业 / 居住 / 休闲类：优先选。"""
    text = str(name or "")
    return any(w in text for w in GOOD_WORDS)


def good_first(pois) -> list:
    """去掉学校类，好地点排前面（中性地点保留在后面）。"""
    clean = [p for p in (pois or []) if not is_bad(p.get("name"))]
    good = [p for p in clean if is_good(p.get("name"))]
    rest = [p for p in clean if not is_good(p.get("name"))]
    return good + rest
